rows = (len(chars)+COLS-1)//COLS
img = Image.new('RGBA', (COLS*CW, rows*CH), (0,0,0,0))
px = img.load(); glyphs = {}
for i,c in enumerate(chars):
    r = G[c].split(); assert all(len(x)==5 for x in r) and len(r) in (7,8,9), c
